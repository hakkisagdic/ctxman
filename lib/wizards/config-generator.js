/**
 * Config Generator
 * Generates configuration files for ctxman
 * FEAT-001: Configuration Wizard
 */

import fs from 'fs';
import path from 'path';

/**
 * Configuration file names
 */
const CONFIG_FILES = {
  contextignore: '.contextignore',
  contextinclude: '.contextinclude',
  methodinclude: '.methodinclude',
};

/**
 * Default minimal configuration
 */
const MINIMAL_CONFIG = {
  contextignore: ['node_modules/', '.git/', 'dist/', 'build/', 'coverage/'],
  contextinclude: ['src/**', 'lib/**'],
  methodinclude: [],
};

class ConfigGenerator {
  /**
   * Create a ConfigGenerator instance
   * @param {string} projectRoot - Project root directory
   */
  constructor(projectRoot = process.cwd()) {
    this.projectRoot = projectRoot;
  }

  /**
   * Check if configuration files exist
   * @returns {object} Object with existence status for each config file
   */
  checkExisting() {
    const existing = {};

    for (const [type, filename] of Object.entries(CONFIG_FILES)) {
      const filePath = path.join(this.projectRoot, filename);
      existing[type] = fs.existsSync(filePath);
    }

    return existing;
  }

  /**
   * Generate configuration files
   * @param {object} config - Configuration object
   * @param {object} options - Generation options
   * @param {boolean} options.force - Overwrite existing files
   * @param {boolean} options.minimal - Use minimal configuration
   * @param {boolean} options.dryRun - Don't write files, just return what would be written
   * @returns {object} Generation result
   */
  generate(config, options = {}) {
    const { force = false, minimal = false, dryRun = false } = options;

    // Use minimal config if requested
    const configToUse = minimal ? MINIMAL_CONFIG : config;

    const result = {
      created: [],
      skipped: [],
      overwritten: [],
      errors: [],
    };

    // Generate each config file
    for (const [type, filename] of Object.entries(CONFIG_FILES)) {
      const patterns = configToUse[type] || [];

      // Skip methodinclude if empty
      if (type === 'methodinclude' && patterns.length === 0) {
        continue;
      }

      const filePath = path.join(this.projectRoot, filename);
      const skip = () =>
        result.skipped.push({
          type,
          filename,
          reason: 'File already exists (use --force to overwrite)',
        });

      if (dryRun) {
        const exists = fs.existsSync(filePath);
        if (exists && !force) {
          skip();
          continue;
        }
        const content = this.generateFileContent(type, patterns);
        (exists ? result.overwritten : result.created).push({ type, filename, content });
        continue;
      }

      const content = this.generateFileContent(type, patterns);
      // Create exclusively first, so an existing file is found by the write itself rather
      // than by a separate check that could be out of date
      try {
        try {
          fs.writeFileSync(filePath, content, { encoding: 'utf-8', flag: 'wx' });
          result.created.push({ type, filename });
        } catch (error) {
          if (error.code !== 'EEXIST') throw error;
          if (!force) {
            skip();
            continue;
          }
          fs.writeFileSync(filePath, content, 'utf-8');
          result.overwritten.push({ type, filename });
        }
      } catch (error) {
        result.errors.push({
          type,
          filename,
          error: error.message,
        });
      }
    }

    return result;
  }

  /**
   * Generate file content for a config type
   * @param {string} type - Config type
   * @param {Array<string>} patterns - Array of patterns
   * @returns {string} File content
   */
  generateFileContent(type, patterns) {
    const header = this.getFileHeader(type);
    const lines = patterns.filter((p) => p && p.trim());

    return header + lines.join('\n') + '\n';
  }

  /**
   * Get header comment for config file
   * @param {string} type - Config type
   * @returns {string} Header comment
   */
  getFileHeader(type) {
    const descriptions = {
      contextignore:
        '# Files and patterns to exclude from context generation\n# One pattern per line\n',
      contextinclude:
        '# Files and patterns to include in context generation\n# One pattern per line\n',
      methodinclude:
        '# Method patterns to include in method-level analysis\n# One pattern per line\n',
    };

    return `# Generated by ctxman init\n# ${descriptions[type] || ''}\n`;
  }

  /**
   * Read existing configuration
   * @returns {object} Existing configuration
   */
  readExisting() {
    const config = {
      contextignore: [],
      contextinclude: [],
      methodinclude: [],
    };

    for (const [type, filename] of Object.entries(CONFIG_FILES)) {
      const filePath = path.join(this.projectRoot, filename);

      if (fs.existsSync(filePath)) {
        try {
          const content = fs.readFileSync(filePath, 'utf-8');
          config[type] = content
            .split('\n')
            .map((line) => line.trim())
            .filter((line) => line && !line.startsWith('#'));
        } catch (_error) {
          // Ignore read errors
        }
      }
    }

    return config;
  }

  /**
   * Merge existing config with new config
   * @param {object} existing - Existing configuration
   * @param {object} newConfig - New configuration
   * @returns {object} Merged configuration
   */
  mergeConfigs(existing, newConfig) {
    const merged = {};

    for (const type of Object.keys(CONFIG_FILES)) {
      const existingPatterns = existing[type] || [];
      const newPatterns = newConfig[type] || [];

      // Combine and deduplicate
      merged[type] = [...new Set([...existingPatterns, ...newPatterns])];
    }

    return merged;
  }

  /**
   * Format config for display
   * @param {object} config - Configuration object
   * @param {string} type - Config type
   * @returns {string} Formatted string
   */
  formatForDisplay(config, type) {
    const patterns = config[type] || [];
    if (patterns.length === 0) {
      return '  (empty)';
    }

    return patterns.map((p) => `  ${p}`).join('\n');
  }

  /**
   * Preview configuration without writing
   * @param {object} config - Configuration object
   * @returns {string} Preview string
   */
  preview(config) {
    const lines = [];

    lines.push('📝 Configuration Preview:');
    lines.push('');

    for (const [type, filename] of Object.entries(CONFIG_FILES)) {
      const patterns = config[type] || [];
      if (type === 'methodinclude' && patterns.length === 0) {
        continue;
      }

      lines.push(`${filename}:`);
      if (patterns.length === 0) {
        lines.push('  (no patterns)');
      } else {
        patterns.forEach((p) => lines.push(`  ${p}`));
      }
      lines.push('');
    }

    return lines.join('\n');
  }
}

export default ConfigGenerator;
export { CONFIG_FILES, MINIMAL_CONFIG };
